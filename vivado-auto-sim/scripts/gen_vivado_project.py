#!/usr/bin/env python3
"""
gen_vivado_project.py — 自动扫描 Verilog 工程，生成 Vivado 行为级仿真 TCL 脚本。

用法:
    python gen_vivado_project.py <工程根目录> [--tb <testbench文件>] [--part <器件型号>]

功能:
    1. 递归扫描所有 .v 文件，自动区分 RTL 和 testbench
    2. 检测 `include 头文件，自动设置 include_dirs
    3. 检测 $readmemh/$readmemb 数据文件，自动拷贝到 xsim 工作目录
    4. 从 testbench 提取顶层模块名
    5. 生成完整的 Vivado TCL 脚本 + 一键启动批处理

输出:
    <工程根目录>/vivado_sim.tcl       — Vivado TCL 脚本
    <工程根目录>/launch_vivado_sim.bat — 一键启动（纯ASCII，避免编码问题）
"""

import os
import re
import sys
import argparse
from pathlib import Path


def find_verilog_files(root):
    """递归查找所有 .v 文件，返回 (rtl_files, tb_files)。"""
    all_v = []
    for dirpath, dirnames, filenames in os.walk(root):
        # 跳过 vivado 工程目录和仿真输出
        dirnames[:] = [d for d in dirnames if d not in (
            'vivado_proj', '.git', '__pycache__', 'simulation', '.xil'
        )]
        for f in filenames:
            if f.endswith('.v') or f.endswith('.sv'):
                all_v.append(os.path.join(dirpath, f))

    rtl_files = []
    tb_files = []
    for f in all_v:
        rel = os.path.relpath(f, root)
        lower = rel.lower()
        if (os.sep + 'tb' + os.sep) in (os.sep + lower) or \
           lower.startswith('tb' + os.sep) or \
           '_tb.v' in lower or '_testbench' in lower or \
           os.path.basename(lower).startswith('tb_'):
            tb_files.append(f)
        else:
            rtl_files.append(f)
    # 优先选择直接在 tb/ 目录下的 testbench（而非子目录中的）
    def tb_priority(f):
        rel = os.path.relpath(f, root).lower()
        depth = rel.count(os.sep)
        return (0 if depth == 1 else 1, rel)
    tb_files.sort(key=tb_priority)
    return rtl_files, tb_files


def find_includes(files):
    """从文件列表中检测 `include "xxx.v"，返回被包含的文件名集合。"""
    includes = set()
    for f in files:
        try:
            with open(f, 'r', encoding='utf-8', errors='ignore') as fh:
                content = fh.read()
            for m in re.finditer(r'`include\s+"([^"]+)"', content):
                includes.add(m.group(1))
        except Exception:
            pass
    return includes


def find_include_dirs(root, include_names):
    """根据被包含的文件名，查找包含这些文件的目录。"""
    dirs = set()
    if not include_names:
        return dirs
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in ('vivado_proj', '.git')]
        for name in include_names:
            if name in filenames:
                dirs.add(dirpath)
    return dirs


def find_readmem_files(files):
    """检测 $readmemh("xxx", ...) / $readmemb("xxx", ...)，返回数据文件名集合。"""
    data_files = set()
    for f in files:
        try:
            with open(f, 'r', encoding='utf-8', errors='ignore') as fh:
                content = fh.read()
            for m in re.finditer(r'\$readmem[bh]\s*\(\s*"([^"]+)"', content):
                data_files.add(m.group(1))
        except Exception:
            pass
    return data_files


def find_data_file_paths(root, data_names):
    """在工程中查找数据文件的实际路径。"""
    paths = {}
    for name in data_names:
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in ('vivado_proj', '.git')]
            if name in filenames:
                paths[name] = os.path.join(dirpath, name)
                break
    return paths


def extract_top_module(tb_file):
    """从 testbench 文件中提取 module 名（跳过注释，匹配行首 module）。"""
    try:
        with open(tb_file, 'r', encoding='utf-8', errors='ignore') as fh:
            for line in fh:
                stripped = line.strip()
                # 跳过注释行和空行
                if not stripped or stripped.startswith('//') or stripped.startswith('/*'):
                    continue
                # 去掉行内注释
                code = stripped.split('//')[0]
                m = re.search(r'\bmodule\s+(\w+)', code)
                if m:
                    return m.group(1)
    except Exception:
        pass
    return os.path.splitext(os.path.basename(tb_file))[0]


def to_tcl_path(p):
    """Windows 路径转 TCL 路径（反斜杠转正斜杠）。"""
    return p.replace('\\', '/')


def generate_tcl(root, rtl_files, tb_files, include_dirs, data_paths,
                 top_module, part='xc7a100tcsg324-1', runtime='10ms'):
    """生成 Vivado TCL 脚本内容。"""
    root_tcl = to_tcl_path(root)
    project_dir = f"{root_tcl}/vivado_proj"
    project_name = "auto_sim"

    lines = []
    lines.append("# Auto-generated by gen_vivado_project.py")
    lines.append(f"# Project root: {root_tcl}")
    lines.append("")
    lines.append("close_project -quiet")
    lines.append("")
    lines.append(f"create_project {project_name} {project_dir} -part {part} -force")
    lines.append("")

    # 添加 RTL 源文件
    lines.append("# === RTL Sources ===")
    for f in sorted(rtl_files):
        lines.append(f'add_files "{to_tcl_path(f)}"')
    lines.append("")

    # 添加 testbench
    lines.append("# === Testbench (sim_1) ===")
    for f in sorted(tb_files):
        lines.append(f'add_files -fileset sim_1 "{to_tcl_path(f)}"')
    lines.append("")

    # 设置 include 路径
    if include_dirs:
        inc_str = " ".join(f'{{{to_tcl_path(d)}}}' for d in sorted(include_dirs))
        lines.append("# === Include Directories ===")
        lines.append(f"set_property include_dirs [list {inc_str}] [get_filesets sources_1]")
        lines.append(f"set_property include_dirs [list {inc_str}] [get_filesets sim_1]")
        lines.append("")

    # 设置仿真顶层
    lines.append("# === Simulation Top ===")
    lines.append(f'set_property top {top_module} [get_filesets sim_1]')
    lines.append('set_property top_lib xil_defaultlib [get_filesets sim_1]')
    lines.append("")

    # 更新编译顺序
    lines.append("update_compile_order -fileset sources_1")
    lines.append("update_compile_order -fileset sim_1")
    lines.append("")

    # 拷贝数据文件到 xsim 工作目录
    if data_paths:
        xsim_dir = f"{project_dir}/{project_name}.sim/sim_1/behav/xsim"
        lines.append("# === Copy Data Files ($readmemh/$readmemb) ===")
        lines.append(f'file mkdir "{xsim_dir}"')
        for name, src in sorted(data_paths.items()):
            lines.append(f'file copy -force "{to_tcl_path(src)}" "{xsim_dir}/{name}"')
            lines.append(f'puts "Copied data file: {name}"')
        lines.append("")

    # 设置仿真运行时间
    lines.append("# === Simulation Settings ===")
    lines.append(f'set_property -name {{xsim.simulate.runtime}} -value {{{runtime}}} -objects [get_filesets sim_1]')
    lines.append("")

    lines.append('puts "============================================================"')
    lines.append('puts "Vivado project created successfully."')
    lines.append(f'puts "Simulation top: {top_module}"')
    lines.append('puts "Next: Run Simulation -> Run Behavioral Simulation"')
    lines.append('puts "============================================================"')

    return "\n".join(lines)


def generate_batch(vivado_path, tcl_path):
    """生成纯 ASCII 批处理启动文件（避免中文编码问题）。"""
    return f"""@echo off
echo ============================================================
echo  Vivado Auto-Simulation Launcher
echo ============================================================
echo.
echo Starting Vivado, please wait...
echo.
start "" "{vivado_path}" -source "{tcl_path}"
echo.
echo Vivado launched. After project creation, click:
echo   Run Simulation -^> Run Behavioral Simulation
echo.
pause
"""


def main():
    parser = argparse.ArgumentParser(description='Generate Vivado simulation project TCL')
    parser.add_argument('root', help='Project root directory')
    parser.add_argument('--tb', help='Specific testbench file (default: auto-detect)')
    parser.add_argument('--part', default='xc7a100tcsg324-1', help='FPGA part number')
    parser.add_argument('--runtime', default='10ms', help='Simulation runtime')
    parser.add_argument('--vivado', default=r'D:\Xilinx\xili\Vivado\2019.1\bin\vivado.bat',
                        help='Path to vivado.bat (for batch launcher)')
    args = parser.parse_args()

    root = os.path.abspath(args.root)
    if not os.path.isdir(root):
        print(f"ERROR: {root} is not a directory", file=sys.stderr)
        sys.exit(1)

    print(f"Scanning project: {root}")

    # 1. 查找文件
    rtl_files, tb_files = find_verilog_files(root)
    print(f"  RTL files: {len(rtl_files)}")
    print(f"  Testbench files: {len(tb_files)}")

    if not tb_files:
        print("ERROR: No testbench found. Put .v files in tb/ directory or name them *_tb.v", file=sys.stderr)
        sys.exit(1)

    # 指定 testbench
    tb_file = args.tb
    if tb_file:
        tb_file = os.path.abspath(tb_file)
        if tb_file not in tb_files:
            tb_files.append(tb_file)
    else:
        tb_file = tb_files[0]
    print(f"  Using testbench: {os.path.relpath(tb_file, root)}")

    # 2. 检测 include
    all_files = rtl_files + tb_files
    include_names = find_includes(all_files)
    include_dirs = find_include_dirs(root, include_names)
    print(f"  Include files: {include_names if include_names else '(none)'}")
    print(f"  Include dirs: {include_dirs if include_dirs else '(none)'}")

    # 3. 检测 readmem 数据文件
    data_names = find_readmem_files(tb_files + rtl_files)
    data_paths = find_data_file_paths(root, data_names)
    print(f"  Data files ($readmem): {data_names if data_names else '(none)'}")
    for name, path in data_paths.items():
        print(f"    {name} -> {os.path.relpath(path, root)}")
    missing_data = data_names - set(data_paths.keys())
    if missing_data:
        print(f"  WARNING: Data files not found in project: {missing_data}", file=sys.stderr)

    # 4. 提取顶层模块
    top_module = extract_top_module(tb_file)
    print(f"  Top module: {top_module}")

    # 5. 生成 TCL（只加选中的 testbench，避免同名模块冲突）
    tcl_content = generate_tcl(
        root, rtl_files, [tb_file], include_dirs, data_paths,
        top_module, args.part, args.runtime
    )
    tcl_path = os.path.join(root, 'vivado_sim.tcl')
    with open(tcl_path, 'w', encoding='utf-8') as f:
        f.write(tcl_content)
    print(f"\nGenerated: {tcl_path}")

    # 6. 生成批处理启动文件
    batch_content = generate_batch(args.vivado, to_tcl_path(tcl_path))
    batch_path = os.path.join(root, 'launch_vivado_sim.bat')
    with open(batch_path, 'w', encoding='ascii') as f:
        f.write(batch_content)
    print(f"Generated: {batch_path}")

    print("\nDone. Double-click launch_vivado_sim.bat to start.")


if __name__ == '__main__':
    main()
